#include<iostream>
using namespace std;


int main(){


    // Bit-Operator And
    cout<<(3 & 5)<<'\n';

    // Bit-Operator OR
    cout<<(3 | 5)<<'\n';

    // Bit-Operator XOR
    cout<<(3 ^ 5)<<'\n';


    // Binary NOT Operator
    cout<<(~0)<<'\n';

    // Binary Left Shift
    cout<< (7<<2) <<'\n';

    // Binary Right Shift
    cout<< (7 >> 2)<<'\n';


    return 0;
}